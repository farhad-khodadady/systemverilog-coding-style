package template_package;

//===================================================================================================================================================
//  Parameters
//===================================================================================================================================================
parameter int DATA_WIDTH = 32;
parameter int ADDR_WIDTH = 16;

//===================================================================================================================================================
//  Typedefs
//===================================================================================================================================================
typedef logic [DATA_WIDTH-1:0] data_t;
typedef logic [ADDR_WIDTH-1:0] addr_t;

//===================================================================================================================================================
//  Function Definitions
//===================================================================================================================================================
function data_t swap_bytes(input data_t in_data);
  data_t swapped_data;
  for (int i = 0; i < DATA_WIDTH/8; i++) begin
    swapped_data[i*8 +: 8] = in_data[(DATA_WIDTH/8 - 1 - i)*8 +: 8];
  end
  return swapped_data;
endfunction : swap_bytes

//===================================================================================================================================================
//  Task Definitions
//===================================================================================================================================================
task automatic print_data(input data_t data);
  $display("Data: %h", data);
endtask : print_data

//===================================================================================================================================================
//  End of Package
//===================================================================================================================================================
endpackage : template_package

